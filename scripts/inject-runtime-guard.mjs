/**
 * Plants the Bun runtime check at the top of the standalone server entry.
 *
 * `vinext build` generates dist/standalone/server.js with a `#!/usr/bin/env
 * node` shebang and prints "Start it with: node dist/standalone/server.js" —
 * both of which point at a runtime this app does not support. Taking that
 * advice gets you ERR_UNSUPPORTED_ESM_URL_SCHEME from a `bun:sqlite` import
 * several layers down, because the app bundle server.js loads fails while its
 * module graph is still linking. No application code runs before that, so the
 * guard in src/lib/runtime-guard.ts cannot catch it from inside — it has to sit
 * ahead of the import that fails.
 *
 * The entry is regenerated by every build, so this runs as the build's last
 * step rather than being committed into the output.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { BUN_REQUIRED_MESSAGE } from "../src/lib/runtime-guard.ts";

const entry = resolve(import.meta.dirname, "..", "dist", "standalone", "server.js");
const MARKER = "// caddy-proxy-manager:runtime-guard";

const guard = `${MARKER}
// Injected by scripts/inject-runtime-guard.mjs — keep in sync with src/lib/runtime-guard.ts.
if (!process.versions.bun) {
  const runtime = process.versions.node ? \`Node.js \${process.versions.node}\` : "an unknown runtime";
  console.error(${JSON.stringify(BUN_REQUIRED_MESSAGE)}.replace("{runtime}", runtime));
  process.exit(1);
}
`;

let source;
try {
  source = readFileSync(entry, "utf8");
} catch (error) {
  console.error(`[runtime-guard] Could not read ${entry}: ${error.message}`);
  process.exit(1);
}

if (source.includes(MARKER)) {
  console.log("[runtime-guard] Already present in dist/standalone/server.js");
  process.exit(0);
}

// The guard must precede every import, and the shebang must stay on line 1 —
// so retarget the shebang at Bun and slot the check in directly beneath it.
const lines = source.split("\n");
const hasShebang = lines[0]?.startsWith("#!");
if (!hasShebang) {
  console.error(
    "[runtime-guard] dist/standalone/server.js has no shebang — the generated entry changed shape, " +
      "so the guard was not injected. Update scripts/inject-runtime-guard.mjs.",
  );
  process.exit(1);
}

const patched = ["#!/usr/bin/env bun", guard, ...lines.slice(1)].join("\n");
writeFileSync(entry, patched);
console.log("[runtime-guard] Guarded dist/standalone/server.js against non-Bun runtimes");
